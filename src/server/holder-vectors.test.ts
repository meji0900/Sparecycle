// Foundry-compatible vectors of the holder-pool root (contracts/test/fixtures/holder-pool-vectors.json, checked by
// contracts/test/v2/HolderPoolVectors.t.sol): the scheduler's split of an epoch's funding (time-weighted weights, floored,
// totalEth = the sum of the leaves), its leaves (keccak256(abi.encodePacked(uint64 epochId, address holder, uint8 mode,
// uint256 amount))), root and proofs. This test rebuilds the vectors with src/server/holders.ts and fails when they drift
// from the committed file; the Foundry test posts each root on SparecycleHolderPool and claims every leaf with these
// proofs as compute credits. Regenerate after an intended change: HOLDER_VECTORS_WRITE=1 npm test. Run: npm test
import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { after, describe, test } from "node:test";
import { getAddress, pad, toHex, type Address, type Hex } from "viem";

for (const k of Object.keys(process.env)) {
  if (/^(NEXT_PUBLIC_|SCHEDULER_|TOKEN_)/.test(k)) delete process.env[k];
}
const dir = mkdtempSync(join(tmpdir(), "sparecycle-holder-vectors-"));
Object.assign(process.env, { NEXT_PUBLIC_NETWORK: "local", NEXT_PUBLIC_RPC_URL: "http://127.0.0.1:9", DB_PATH: join(dir, "test.db") });
after(() => rmSync(dir, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 }));

const H = await import("./holders");
const { verifyProof } = await import("@/lib/merkle");
const { HOLDER_MODE } = await import("@/lib/token-rules");

const FILE = join(import.meta.dirname, "..", "..", "contracts", "test", "fixtures", "holder-pool-vectors.json");
const SPARE = 10n ** 18n;
const who = (n: number) => getAddress(pad(toHex(n), { size: 20 })) as Address;

/** Labelled inputs: synthetic holders and weights (time-weighted SPARE), test funding amounts. Not market data. */
const INPUTS: { epochId: number; fundedWei: bigint; weights: [Address, bigint][]; note: string }[] = [
  {
    epochId: 3,
    fundedWei: 10n ** 18n + 7n,
    weights: [
      [who(0xa11ce), 100_000n * SPARE],
      [who(0xb0b), 300_000n * SPARE],
      [who(0xca401), 600_000n * SPARE],
    ],
    note: "three holders 1:3:6; the 1 wei remainder stays in the pool",
  },
  { epochId: 4, fundedWei: 12_345n, weights: [[who(0xd00d), 250_000n * SPARE + 1n]], note: "one holder: the leaf is the root, empty proof" },
  {
    epochId: 5,
    fundedWei: 3n * 10n ** 16n + 1n,
    weights: [
      [who(0xe1), 123_456n * SPARE + 789n],
      [who(0xe2), 7_777_777n * SPARE],
      [who(0xe3), 100_000n * SPARE],
      [who(0xe4), 2_500_000n * SPARE + 3n],
      [who(0xe5), 999_999n * SPARE + 999n],
    ],
    note: "five holders (odd count: a node is promoted unchanged), uneven weights",
  },
];

function buildVectors() {
  return {
    note: "Generated by src/server/holder-vectors.test.ts from src/server/holders.ts (HOLDER_VECTORS_WRITE=1 npm test). Synthetic holders and test amounts.",
    leafRule: "keccak256(abi.encodePacked(uint64 epochId, address holder, uint8 mode, uint256 amount)); OpenZeppelin sorted-pair tree",
    cases: INPUTS.map((c) => {
      const shares = H.allocateHolderShares(c.fundedWei, new Map(c.weights));
      const { tree, leaves } = H.buildHolderTree(
        c.epochId,
        shares.map((s) => ({ ...s, mode: HOLDER_MODE.credits })),
      );
      return {
        note: c.note,
        epochId: c.epochId,
        funded: c.fundedWei.toString(),
        total: leaves.reduce((s, l) => s + l.amount, 0n).toString(),
        root: tree.root,
        holders: leaves.map((l) => l.holder),
        weights: leaves.map((l) => l.weight.toString()),
        modes: leaves.map((l) => l.mode),
        amounts: leaves.map((l) => l.amount.toString()),
        leaves: leaves.map((l) => l.leaf),
        proofs: leaves.map((l) => l.proof),
      };
    }),
  };
}

describe("holder-pool vectors for Foundry", () => {
  const built = buildVectors();
  if (process.env.HOLDER_VECTORS_WRITE === "1") writeFileSync(FILE, `${JSON.stringify(built, null, 2)}\n`);

  test("the committed vectors are what holders.ts builds today", () => {
    const committed = JSON.parse(readFileSync(FILE, "utf8"));
    assert.deepEqual(committed, JSON.parse(JSON.stringify(built)));
  });

  test("each amount is the floored time-weighted share; the remainder (< holders, in wei) stays in the pool", () => {
    for (const c of built.cases) {
      const funded = BigInt(c.funded);
      const sumW = c.weights.reduce((s, w) => s + BigInt(w), 0n);
      c.amounts.forEach((a, i) => assert.equal(BigInt(a), (funded * BigInt(c.weights[i])) / sumW, `case ${c.epochId} holder ${i}`));
      const total = BigInt(c.total);
      assert.equal(total, c.amounts.reduce((s, a) => s + BigInt(a), 0n));
      assert.ok(total <= funded && funded - total < BigInt(c.amounts.length), `case ${c.epochId}: remainder ${funded - total}`);
    }
    assert.equal(built.cases[0].total, (10n ** 18n + 6n).toString(), "1:3:6 of 1 ETH + 7 wei: 0.1 + 0.3 + 0.6 ETH + 6 wei");
  });

  test("every proof verifies against its root with the contract's leaf rule", () => {
    for (const c of built.cases) {
      c.leaves.forEach((leaf, i) => {
        assert.equal(leaf, H.holderLeafOf(BigInt(c.epochId), c.holders[i] as Address, c.modes[i], BigInt(c.amounts[i])));
        assert.ok(verifyProof(c.proofs[i] as Hex[], c.root as Hex, leaf as Hex), `case ${c.epochId} leaf ${i}`);
      });
    }
    assert.deepEqual(built.cases[1].proofs, [[]]);
    assert.equal(built.cases[1].root, built.cases[1].leaves[0]);
  });
});

describe("allocateHolderShares (rounding)", () => {
  test("floors every share, never exceeds the total, drops zero shares", () => {
    const a = who(1);
    const b = who(2);
    const c = who(3);
    const s = H.allocateHolderShares(10n, new Map([[a, 1n], [b, 1n], [c, 1n]]));
    assert.deepEqual(s.map((x) => x.amount), [3n, 3n, 3n]);
    assert.deepEqual(H.allocateHolderShares(2n, new Map([[a, 1n], [b, 1n], [c, 1n]])), [], "2 wei over 3 holders: every share is 0");
    assert.deepEqual(H.allocateHolderShares(0n, new Map([[a, 1n]])), []);
    assert.deepEqual(H.allocateHolderShares(5n, new Map()), []);
    const one = H.allocateHolderShares(7n, new Map([[a, 10n ** 30n], [b, 1n]]));
    assert.deepEqual(one.map((x) => [x.holder, x.amount]), [[a, 6n]], "the tiny weight rounds to 0 and is dropped");
  });

  test("random weights: sum <= total, remainder < number of holders, each share exact (500 runs)", () => {
    let seed = 0x5eed;
    const rnd = (bits: number) => {
      let v = 0n;
      for (let i = 0; i < bits; i += 16) {
        seed = (seed * 1103515245 + 12345) & 0x7fffffff;
        v = (v << 16n) | BigInt(seed & 0xffff);
      }
      return v;
    };
    for (let run = 0; run < 500; run++) {
      const n = 1 + Number(rnd(16) % 12n);
      const weights = new Map<Address, bigint>();
      for (let i = 0; i < n; i++) weights.set(who(0x1000 + i), 1n + rnd(96));
      const total = rnd(80);
      const shares = H.allocateHolderShares(total, weights);
      const sumW = [...weights.values()].reduce((s, w) => s + w, 0n);
      const sum = shares.reduce((s, x) => s + x.amount, 0n);
      assert.ok(sum <= total);
      assert.ok(total - sum < BigInt(n));
      for (const x of shares) assert.equal(x.amount, (total * weights.get(x.holder)!) / sumW);
    }
  });
});
